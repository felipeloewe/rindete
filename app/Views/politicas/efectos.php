    <h3>Ley N° 19.628, sobre protección de la vida privada</h3>
    <p>Es la norma que hoy rige el tratamiento.</p>
    <ul>
        <li>La empresa pide nombre, correo, RUT y cuenta bancaria de quien rinde, y esa persona acepta ese uso antes de rendir.</li>
        <li>Esos datos identifican a quien rinde, permiten pagar el fondo y anotan el RUT en el preasiento cuando la empresa lo pide.</li>
        <li>Quien rinde puede pedir a su empresa ver, corregir o dejar de usar sus datos. Rindete aplica ese pedido en la cuenta de la empresa.</li>
    </ul>
    <h3>Ley N° 21.719, sobre protección de datos personales</h3>
    <p>Rindete la considera desde ya. Entra en vigencia en la fecha que fije la ley: el artículo primero transitorio señala el 1 de diciembre de 2026, y el Congreso despachó una postergación al 15 de octubre de 2027 que todavía debe promulgarse y publicarse.</p>
    <ul>
        <li>La empresa es responsable de los datos de quien rinde. Rindete los trata por cuenta de la empresa para prestar el software.</li>
        <li>Del correo y de la clave de acceso responde Rindete, porque los necesita para entregar la cuenta.</li>
        <li>Se guarda lo que la rendición necesita. El nombre, el correo, el RUT y la cuenta viven en la capa de identidades; la operación guarda el id. Cuando la ley entre en vigencia, los derechos que ella reconozca se ejercen ante la empresa y Rindete los atiende en esa cuenta.</li>
    </ul>
    <h3>Ley N° 20.575, principio de finalidad</h3>
    <p>El dato se usa para el fin con el que se pidió.</p>
    <ul>
        <li>El RUT y la cuenta bancaria identifican a quien rinde y arman la nómina del fondo.</li>
        <li>La foto del comprobante respalda el gasto.</li>
        <li>Quedan fuera la evaluación de crédito, el envío a una base comercial y cualquier fin distinto de rendir.</li>
    </ul>
    <h3>Ley N° 19.799, documentos electrónicos y firma electrónica</h3>
    <p>El registro del servicio es electrónico.</p>
    <ul>
        <li>El comprobante, el gasto, el fondo y el preasiento quedan como registros electrónicos del servicio.</li>
        <li>La aceptación de estas condiciones queda guardada con esta versión y la fecha.</li>
        <li>Esos registros respaldan la rendición. No sustituyen una firma electrónica avanzada ni un certificado de firma.</li>
    </ul>
    <h3>Ley N° 19.496, protección de los derechos de los consumidores</h3>
    <p>En lo que alcanza al contrato de uso del software.</p>
    <ul>
        <li>El alta informa el plan Free: 4 usuarios y 2 GB.</li>
        <li>La empresa administra a sus personas, los topes y el cierre. Cada persona usa lo que esa empresa le habilitó.</li>
        <li>Los preasientos y el seguimiento de cuentas se contratan aparte. El alta del plan Free no incluye un cobro por esos módulos.</li>
    </ul>
    <h3>Ley N° 21.459, delitos informáticos</h3>
    <p>El uso del software tiene un límite.</p>
    <ul>
        <li>Cada persona entra con su propia cuenta.</li>
        <li>El comprobante, el fondo y el preasiento se registran como ocurrieron.</li>
        <li>Entrar a los datos de otra empresa o saltar el acceso queda fuera del servicio y sujeto a esta ley. Aceptar estas condiciones no cubre ese uso.</li>
    </ul>
